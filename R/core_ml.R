#' calculateEvalMets()
#'
#' Returns the F1 score, area under the precision-recall curve (AUPRC), balanced
#' accuracy, normalized (to a 0 to 1 scale instead of -1 to 1) Matthews
#' correlation coefficient (nMCC), and log2(AUPRC/prior) based on the AMR
#' phenotype predictions by an ML model compared against the actual values.
#'
#' @inheritParams getConfusionMatrix
#' @return F1 score, AUPRC, balanced accuracy, nMCC, and log2(AUPRC/prior)
#' @examples
#' preds <- tibble::tibble(
#'   genome_id = paste0("g", 1:10),
#'   genome_drug.resistant_phenotype = factor(
#'     rep(c("Resistant", "Susceptible"), each = 5),
#'     levels = c("Resistant", "Susceptible")
#'   ),
#'   .pred_class = factor(
#'     c(
#'       "Resistant", "Resistant", "Susceptible", "Resistant", "Susceptible",
#'       "Susceptible", "Resistant", "Susceptible", "Susceptible", "Resistant"
#'     ),
#'     levels = c("Resistant", "Susceptible")
#'   ),
#'   .pred_Resistant = c(0.9, 0.8, 0.4, 0.7, 0.3, 0.2, 0.6, 0.1, 0.2, 0.55),
#'   .pred_Susceptible = c(0.1, 0.2, 0.6, 0.3, 0.7, 0.8, 0.4, 0.9, 0.8, 0.45)
#' )
#' calculateEvalMets(preds)
#' @export
calculateEvalMets <- function(test_data_plus_predictions) {
  .checkArgTestDataPlusPredictions(test_data_plus_predictions)

  f1 <- .calculateF1(test_data_plus_predictions)
  auprc <- .calculateAUPRC(test_data_plus_predictions)
  bal_acc <- .calculateBalAcc(test_data_plus_predictions)
  sens <- .calculateSensitivity(test_data_plus_predictions)
  spec <- .calculateSpecificity(test_data_plus_predictions)
  nmcc <- .calculatenMCC(test_data_plus_predictions)
  log2_apop <- .calculateLog2APOP(test_data_plus_predictions)

  return(c(f1, auprc, bal_acc, nmcc, log2_apop))
}

#' extractTopFeats()
#'
#' Returns the top features that an ML model found to be important for
#' predicting the AMR phenotype of a given pathogen.
#'
#' @param fit Best model fit, such as the output of `fitBestModel()`
#' @param prop_vi_top_feats [num] A vector of length 2 with elements together
#' indicating the proportion of total variable importance the top features
#' should comprise. To get the features that contribute to the top 10 to 20% of
#' total variable importance, for example, set
#' `prop_vi_top_feats = c(0.1, 0.2)`.
#' Returns all features by default.
#' @param n_top_feats [num] Number of top features to extract
#' @return A tibble with a column for top features (`Variable`), a column for
#' `Importance`, and a column for `Sign` (or, for multi-class, a tibble with
#' per-class columns of importance scores for each `Variable`)
#' @examples
#' data(demo_fit)
#' extractTopFeats(demo_fit, n_top_feats = 10)
#' @export
extractTopFeats <- function(
  fit, prop_vi_top_feats = c(0, 1),
  n_top_feats = NA
) {
  .checkArgWflow(fit)

  if (!is.na(n_top_feats)) {
    prop_vi_top_feats <- NA
  }

  # Arg checking for every permutation of `prop_vi_top_feats` and `n_top_feats`
  if (is.na(n_top_feats) & any(!is.na(prop_vi_top_feats))) {
    .checkArgPropVITopFeats(prop_vi_top_feats)
  } else if (any(is.na(prop_vi_top_feats)) & !is.na(n_top_feats)) {
    .checkArgNTopFeats(n_top_feats)
  } else if (any(!is.na(prop_vi_top_feats)) & !is.na(n_top_feats)) {
    stop("Set either `n_top_feats` or `prop_vi_top_feats` to `NA` but not
      both.")
  } else if (any(is.na(prop_vi_top_feats)) & is.na(n_top_feats)) {
    stop("Please specify either `n_top_feats` or `prop_vi_top_feats`.")
  }

  feats_arranged <- fit |>
    workflowsets::extract_fit_parsnip() |>
    vip::vi() |>
    dplyr::arrange(dplyr::desc(Importance))

  if (!is.na(n_top_feats)) {
    top_feats_and_VIs <- feats_arranged |> dplyr::slice(1:n_top_feats)
  } else if (any(!is.na(prop_vi_top_feats))) {
    cum_vi_lower <- prop_vi_top_feats[1] * sum(feats_arranged$Importance)
    cum_vi_upper <- prop_vi_top_feats[2] * sum(feats_arranged$Importance)

    top_feats_and_VIs <- feats_arranged |>
      dplyr::mutate(cum_imp = cumsum(Importance)) |>
      dplyr::filter(cum_imp < cum_vi_upper & cum_imp > cum_vi_lower)
  }

  top_feat_tibble <- tibble::tibble(
    Variable = dplyr::pull(top_feats_and_VIs, Variable),
    Importance = dplyr::pull(top_feats_and_VIs, Importance),
    Sign = dplyr::pull(top_feats_and_VIs, Sign)
  )

  # Take a different approach if using multi-class (the previous code would give
  # a less meaningful result).
  if (is(fit$fit$actions$model$spec, "multinom_reg")) {
    warning(paste(
      "Extracting top features from a multi-class model.",
      "The `prop_vi_top_feats` and `n_top_feats` arguments do not apply."
    ))

    fit_penalty <- .getFitHps(fit)["penalty"] |> as.numeric()
    glmnet_fit <- parsnip::extract_fit_engine(fit)
    coefs <- stats::coef(glmnet_fit, s = fit_penalty)

    importance_table <- purrr::imap_dfr(coefs, function(mat, class) {
      mat_dense <- as.matrix(mat)
      tibble::tibble(
        class = class,
        Variable = rownames(mat_dense)[-1], # Exclude intercept.
        coefficient = mat_dense[-1, 1] # Get coefficients as numeric vector.
      )
    })

    top_feat_tibble <- importance_table |>
      dplyr::select(Variable, class, coefficient) |>
      tidyr::pivot_wider(
        names_from = class,
        values_from = coefficient,
        values_fill = 0 # Fill missing values with 0.
      ) |>
      dplyr::filter(dplyr::if_any(-Variable, ~ . != 0))
  }

  return(top_feat_tibble)
}
